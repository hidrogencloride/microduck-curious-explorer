/**
 * Curious Explorer — a small, additive behavior layer.
 *
 * This dependency-free module runs in a browser or in Node. It models a character
 * in a normalized practice field; it is not a physics simulator or a robot SDK.
 * start(), pause(), observe(), setSettings(), setSkills(), setAllowedSkills(),
 * and resetMemory() return a detached snapshot. tick(seconds) returns only newly
 * requested semantic actions. A separate, explicitly armed adapter may translate
 * these requests into supported simulator commands.
 *
 * No method installs, removes, replaces, or edits a robot skill. setSkills() only
 * refreshes our local view of a read-only capability listing. Explicit permission
 * is required before an installed gesture can be requested. Gaits are never
 * selected or replaced. pause() clears all pending requests; the adapter must
 * also stop its own in-flight activity immediately when the owner pauses it.
 *
 * Coordinates are normalized to [0, 1]; heading, yaw, and pitch use radians.
 * move.speed is a conservative requested speed in m/s, not a measured velocity.
 * The practice field uses its own illustrative scale. Observation events are
 * supplied by the host; they are not evidence of camera or object recognition.
 */

export const DEFAULT_SETTINGS = Object.freeze({
  name: 'Explorer',
  curiosity: 70,
  energy: 65,
  sounds: true,
});

/** Example inventory for the practice field, not a discovered robot inventory. */
export const PREVIEW_SKILLS = Object.freeze([
  Object.freeze({
    id: 'custom-gait',
    name: 'Custom walking style',
    label: 'Custom walking style',
    description: 'An example owner-installed gait. Explorer leaves it in place.',
    kind: 'gait',
    preview: true,
  }),
  Object.freeze({
    id: 'polite-bow',
    name: 'Polite bow',
    label: 'Polite bow',
    description: 'An example greeting skill. Used only with your permission.',
    kind: 'skill',
    role: 'greeting',
    preview: true,
  }),
]);

const OBSERVATIONS = ['movement', 'object', 'greeting', 'obstacle'];
const MODES = new Set(['paused', 'exploring', 'resting', 'waiting']);
const clone = (value) => JSON.parse(JSON.stringify(value));
const clamp = (value, min, max) => Math.min(max, Math.max(min, value));
const finite = (value, fallback) => typeof value === 'number' && Number.isFinite(value) ? value : fallback;
const nonnegative = (value) => Math.max(0, finite(value, 0));
const wrapAngle = (value) => Math.atan2(Math.sin(value), Math.cos(value));

function cleanText(value, fallback, maxLength = 60) {
  if (typeof value !== 'string') return fallback;
  return value.replace(/[\u0000-\u001f\u007f]/g, '').trim().slice(0, maxLength) || fallback;
}

function cleanSettings(patch = {}, current = DEFAULT_SETTINGS) {
  if (!patch || typeof patch !== 'object') return { ...current };
  return {
    name: cleanText(patch.name, current.name, 32),
    curiosity: clamp(finite(patch.curiosity, current.curiosity), 0, 100),
    energy: clamp(finite(patch.energy, current.energy), 0, 100),
    sounds: typeof patch.sounds === 'boolean' ? patch.sounds : current.sounds,
  };
}

function emptyMemory() {
  return {
    encounters: 0,
    observations: { movement: 0, object: 0, greeting: 0, obstacle: 0 },
    distance: 0,
    sessions: 0,
    notes: [],
  };
}

function cleanMemory(value = {}) {
  const memory = emptyMemory();
  if (!value || typeof value !== 'object') return memory;
  memory.encounters = Math.floor(nonnegative(value.encounters));
  memory.distance = nonnegative(value.distance);
  memory.sessions = Math.floor(nonnegative(value.sessions));
  for (const type of OBSERVATIONS) {
    memory.observations[type] = Math.floor(nonnegative(value.observations?.[type]));
  }
  // Only fixed, nonpersonal notes generated by this module are kept on restore.
  const knownNotes = new Set([
    'Paused to inspect an object.',
    'Turned toward a movement.',
    'Received a greeting.',
    'Stopped at an obstacle.',
  ]);
  memory.notes = Array.isArray(value.notes)
    ? value.notes.filter((note) => knownNotes.has(note)).slice(0, 8)
    : [];
  return memory;
}

function cleanSkills(value) {
  if (!Array.isArray(value)) return [];
  const seen = new Set();
  return value.flatMap((entry) => {
    if (!entry || typeof entry !== 'object') return [];
    const id = cleanText(entry.id ?? entry.name, '', 128);
    if (!id || seen.has(id)) return [];
    seen.add(id);
    const name = cleanText(entry.name ?? entry.label, id, 100);
    const kind = cleanText(entry.kind, 'skill', 30);
    return [{
      id,
      name,
      label: cleanText(entry.label, name, 100),
      description: cleanText(entry.description, '', 240),
      kind,
      ...(entry.role === 'greeting' ? { role: 'greeting' } : {}),
      ...(typeof entry.preview === 'boolean' ? { preview: entry.preview } : {}),
    }];
  });
}

function isGesture(skill) {
  return !['gait', 'locomotion', 'walking', 'system', 'recovery'].includes(skill.kind);
}

export class Explorer {
  constructor({ settings, memory, clock } = {}) {
    this._settings = cleanSettings(settings);
    this._memory = cleanMemory(memory);
    this._clock = typeof clock === 'function' ? clock : () => new Date();
    this._skills = cleanSkills(PREVIEW_SKILLS);
    this._allowedSkills = [];
    this._mode = 'paused';
    this._mood = 'Ready when you are';
    this._energy = 86;
    this._position = { x: 0.5, y: 0.55, heading: 0 };
    this._focus = { text: 'A little room to wonder.', type: 'idle' };
    this._journal = [];
    this._eventId = 0;
    this._pending = [];
    this._action = null;
    this._untilAction = 0;
    this._holdRemaining = 0;
    this._motionRemaining = 0;
    this._sequence = 0;
    this._log('ready', 'Explorer is ready. Start whenever you like.');
  }

  start() {
    if (this._mode !== 'paused') return this.snapshot();
    this._memory.sessions += 1;
    this._pending = [];
    this._action = null;
    this._untilAction = 0;
    this._holdRemaining = 0;
    this._motionRemaining = 0;
    this._mode = this._energy <= 20 ? 'resting' : 'exploring';
    this._mood = this._mode === 'resting' ? 'Taking a breather' : 'Quietly curious';
    this._focus = { text: 'Let’s see what’s nearby.', type: 'explore' };
    this._log('start', `${this._settings.name} is exploring.`);
    return this.snapshot();
  }

  pause(reason = 'owner') {
    const wasActive = this._mode !== 'paused';
    this._mode = 'paused';
    this._pending = [];
    this._motionRemaining = 0;
    this._action = null;
    this._mood = 'At ease';
    this._focus = {
      text: reason === 'owner_control' ? 'You have the controls.' : 'Taking a little pause.',
      type: 'paused',
    };
    if (wasActive) this._log('pause', reason === 'owner_control'
      ? 'Explorer paused for your controls. Resume when you are ready.'
      : 'Explorer is paused.');
    return this.snapshot();
  }

  /** Update local settings only. Does not alter any robot configuration. */
  setSettings(patch) {
    this._settings = cleanSettings(patch, this._settings);
    if (!this._settings.sounds) {
      this._pending = this._pending.filter((action) => action.kind !== 'sound');
      if (this._action?.kind === 'sound') this._action = null;
    }
    return this.snapshot();
  }

  /** Replace only our local capability view, never the installed robot skills. */
  setSkills(skills) {
    this._skills = cleanSkills(skills);
    this._prunePermissions(this._allowedSkills);
    return this.snapshot();
  }

  setAllowedSkills(ids) {
    this._prunePermissions(Array.isArray(ids) ? ids : []);
    return this.snapshot();
  }

  _prunePermissions(ids) {
    const candidates = new Set(ids.filter((id) => typeof id === 'string'));
    this._allowedSkills = this._skills
      .filter((skill) => candidates.has(skill.id) && isGesture(skill))
      .map((skill) => skill.id);
    const allowed = new Set(this._allowedSkills);
    this._pending = this._pending.filter((action) => action.kind !== 'skill' || allowed.has(action.skillId));
    if (this._action?.kind === 'skill' && !allowed.has(this._action.skillId)) this._action = null;
  }

  /** Clear persona memory without resetting settings, permissions, or inventory. */
  resetMemory() {
    this._memory = emptyMemory();
    this._journal = [];
    this._log('memory', 'A fresh page. Explorer’s memories have been cleared.');
    return this.snapshot();
  }

  observe(type, payload = {}) {
    if (type === 'owner_control') return this.pause('owner_control');
    if (!OBSERVATIONS.includes(type) && type !== 'quiet') return this.snapshot();
    // Paused and resting characters do not queue reactions for a later restart.
    if (this._mode === 'paused') return this.snapshot();
    payload = payload && typeof payload === 'object' ? payload : {};
    if (type === 'quiet') {
      this._pending = [];
      this._motionRemaining = 0;
      this._mode = 'waiting';
      this._holdRemaining = 6;
      this._mood = 'Enjoying the quiet';
      this._focus = { text: 'A moment to listen.', type: 'quiet' };
      this._queue({ kind: 'stop', reason: 'quiet' });
      this._log('quiet', 'Explorer settled down for a quiet moment.');
      return this.snapshot();
    }

    this._memory.encounters += 1;
    this._memory.observations[type] += 1;
    this._untilAction = this._activityDelay();

    if (type === 'obstacle') {
      this._pending = [];
      this._motionRemaining = 0;
      this._mode = 'resting';
      this._holdRemaining = 5;
      this._position.heading = wrapAngle(this._position.heading + Math.PI * 0.72);
      this._mood = 'Giving it some space';
      this._focus = { text: 'Something is in the way. Let’s pause.', type: 'obstacle' };
      this._queue({ kind: 'stop', reason: 'obstacle' });
      this._remember('Stopped at an obstacle.');
      this._log('obstacle', 'Explorer stopped and is giving the obstacle some room.');
      return this.snapshot();
    }

    if (this._mode === 'resting' || this._mode === 'waiting') return this.snapshot();
    this._motionRemaining = 0;
    this._pending = [];
    const yaw = clamp(finite(payload.yaw, (this._memory.encounters % 2 ? 0.28 : -0.28)), -0.65, 0.65);
    this._queue({ kind: 'stop', reason: 'attention' });
    this._queue({ kind: 'look', yaw, pitch: type === 'object' ? -0.12 : 0.06, duration: 1.1 });

    if (type === 'greeting') {
      this._mood = 'Pleased to see you';
      this._focus = { text: 'Oh, hello there.', type: 'greeting' };
      const greeting = this._skills.find((skill) => this._allowedSkills.includes(skill.id)
        && isGesture(skill)
        && (skill.role === 'greeting' || /(?:^|[ _-])bow(?:$|[ _-])/i.test(skill.id)));
      if (greeting) this._queue({ kind: 'skill', skillId: greeting.id });
      if (this._settings.sounds) this._queue({ kind: 'sound', name: 'friendly-chirp' });
      this._remember('Received a greeting.');
      this._log('greeting', greeting
        ? `A little hello, with ${greeting.name.toLowerCase()}.`
        : 'A little head tilt to say hello.');
    } else if (type === 'object') {
      this._mood = 'Wondering about that';
      this._focus = { text: 'Now, what could that be?', type: 'object' };
      this._remember('Paused to inspect an object.');
      this._log('object', 'Explorer paused for a closer look at the practice object.');
      if (this._settings.sounds) this._queue({ kind: 'sound', name: 'curious-chirp' });
    } else {
      this._mood = 'Something caught my eye';
      this._focus = { text: 'Was that a little movement?', type: 'movement' };
      this._remember('Turned toward a movement.');
      this._log('movement', 'Explorer turned toward a movement in the practice field.');
    }
    return this.snapshot();
  }

  /** Advance at most ten seconds per call; return only new semantic requests. */
  tick(dtSeconds = 1) {
    const dt = clamp(finite(dtSeconds, 0), 0, 10);
    if (this._mode === 'paused' || dt === 0) return [];
    const requests = this._pending.splice(0);

    if (this._mode === 'resting' || this._mode === 'waiting') {
      this._energy = clamp(this._energy + dt * 3, 0, 100);
      this._holdRemaining = Math.max(0, this._holdRemaining - dt);
      if (this._holdRemaining === 0 && this._energy >= 68) {
        this._mode = 'exploring';
        this._mood = 'Ready for another look';
        this._focus = { text: 'There’s still a little more to see.', type: 'explore' };
        this._untilAction = 0.8;
        this._log('rest', 'Rested and ready to explore again.');
      }
      return this._finishRequests(requests);
    }

    this._energy = clamp(this._energy - dt * (0.13 + this._settings.energy * 0.003), 0, 100);
    if (this._energy <= 20) {
      this._mode = 'resting';
      this._mood = 'Taking a breather';
      this._focus = { text: 'A small rest before the next discovery.', type: 'rest' };
      this._motionRemaining = 0;
      this._holdRemaining = 5;
      this._log('rest', 'Explorer found a quiet moment to recharge.');
      return this._finishRequests([{ kind: 'stop', reason: 'rest' }]);
    }

    if (this._motionRemaining > 0) {
      const moveTime = Math.min(dt, this._motionRemaining);
      const distance = moveTime * (0.012 + this._settings.energy * 0.00008);
      const nextX = this._position.x + Math.cos(this._position.heading) * distance;
      const nextY = this._position.y + Math.sin(this._position.heading) * distance;
      if (nextX < 0.08 || nextX > 0.92 || nextY < 0.08 || nextY > 0.92) {
        this._position.heading = wrapAngle(this._position.heading + Math.PI * 0.72);
        this._motionRemaining = 0;
        this._untilAction = 2;
        this._focus = { text: 'Let’s stay in our little clearing.', type: 'boundary' };
        requests.push({ kind: 'stop', reason: 'practice-boundary' });
      } else {
        this._position.x = nextX;
        this._position.y = nextY;
        this._memory.distance += distance;
        this._motionRemaining -= moveTime;
      }
    }

    this._untilAction -= dt;
    // New event reactions get their own moment, without an unrelated idle action.
    if (this._untilAction <= 0 && requests.length === 0) {
      this._sequence += 1;
      this._untilAction = this._activityDelay();
      if (this._sequence % 2 === 1) {
        const yaw = Math.sin(this._sequence * 1.7) * 0.42;
        this._mood = 'Quietly curious';
        this._focus = { text: 'A glance this way. A glance that way.', type: 'look' };
        requests.push({ kind: 'look', yaw, pitch: 0.04, duration: 1.2 });
      } else {
        this._position.heading = wrapAngle(this._position.heading + Math.sin(this._sequence * 0.9) * 0.55);
        this._motionRemaining = 1.4;
        this._focus = { text: 'Just a few small steps.', type: 'move' };
        requests.push({ kind: 'move', speed: 0.02 + this._settings.energy * 0.0002, turn: 0, duration: 1.4 });
      }
    }
    return this._finishRequests(requests);
  }

  snapshot() {
    return clone({
      mode: MODES.has(this._mode) ? this._mode : 'paused',
      mood: this._mood,
      energy: this._energy,
      position: this._position,
      focus: this._focus,
      memory: this._memory,
      skills: this._skills,
      allowedSkills: this._allowedSkills,
      settings: this._settings,
      journal: this._journal,
      action: this._action,
    });
  }

  _activityDelay() {
    return 1.8 + (100 - this._settings.curiosity) * 0.025;
  }

  _queue(action) {
    if (this._mode !== 'paused') this._pending.push(action);
  }

  _finishRequests(requests) {
    // Recheck permissions at the last possible point, after inventory updates.
    const allowed = new Set(this._allowedSkills);
    const valid = requests.filter((action) =>
      (action.kind !== 'sound' || this._settings.sounds)
      && (action.kind !== 'skill' || allowed.has(action.skillId)));
    if (valid.length) this._action = clone(valid[valid.length - 1]);
    return clone(valid);
  }

  _remember(note) {
    this._memory.notes = [note, ...this._memory.notes.filter((entry) => entry !== note)].slice(0, 8);
  }

  _log(type, text) {
    const clockValue = this._clock();
    const date = clockValue instanceof Date ? clockValue : new Date(clockValue);
    this._journal.unshift({
      id: ++this._eventId,
      time: Number.isNaN(date.getTime()) ? new Date(0).toISOString() : date.toISOString(),
      type,
      text,
    });
    this._journal = this._journal.slice(0, 60);
  }
}
